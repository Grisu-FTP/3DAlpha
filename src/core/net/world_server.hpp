// The host's world, as the serving half needs it. Implemented by the platform:
// reading a column needs the grid and writing a block needs a renderer, and
// neither of those belongs in core/net.
class ServerWorld {
public:
    virtual ~ServerWorld() = default;

    // A column that is resident right now, or null. Good only for the length
    // of the call -- the grid drops columns in `update()`.
    virtual const world::ChunkColumn* column(i32 chunkX, i32 chunkZ) const = 0;

    // level.dat's running tick count, and the spawn point.
    virtual i64 timeTicks() const = 0;
    virtual void spawnPoint(i32* x, i32* y, i32* z) const = 0;

    // **`kh.q()` -- preparePlayerToSpawn -- for somebody else.** The spawn
    // point in level.dat is a block coordinate with no promise that anything
    // above it is air: a1.1.2 stands a fresh player at `spawnY + 1` and then
    // walks them up until nothing collides, and a server does the same for
    // every login. Without it a guest arrives inside the hillside that has
    // grown over the spawn point since the world was made, which in Survival
    // is a suffocation with no visible cause.
    //
    // Called with the column under the feet already resident, because the
    // placement is only sent once it has been -- see `streamColumns`. The
    // default does nothing, which is what a test with no blocks wants.
    virtual double settleFeet(double x, double feetY, double z) const
    {
        (void)x;
        (void)z;
        return feetY;
    }

    // **A guest's left click that finished a block.** The host runs it through
    // the same break the player's own click does, so the drop, the particles,
    // the neighbour updates and the lighting all happen once, here.
    //
    // **`heldItem` is what decides whether anything drops**, and leaving it out
    // is what made a guest's mining drop nothing at all. `in.c(III)Z` in the
    // 0.2.1 server ends `if (removed && player.canHarvestBlock(block))
    // block.harvestBlock(...)`, so the drop is the digger's tool's, not the
    // host's -- stone under a bare hand leaves nothing and under a pickaxe
    // leaves cobblestone, decided here because the guest's world has no item
    // entities of its own. It is `player.heldItem`, which the guest keeps
    // current with a Holding Change ahead of every dig and every place.
    virtual void breakBlock(i32 x, int y, i32 z, int heldItem) = 0;

    // **A guest's right click on a face**, with everything `item::rightClick`
    // needs that only the guest knows: what they are standing in, so a block
    // cannot be placed inside them, and which way they face, so a stair or a
    // chest lands the right way round.
    struct PlaceRequest {
        i32 x = 0;
        int y = 0;
        i32 z = 0;
        int face = 0;
        int item = 0;
        double playerX = 0.0;
        double playerFeetY = 0.0;
        double playerZ = 0.0;
        float yawDegrees = 0.0f;
    };
    virtual void placeBlock(const PlaceRequest& request) = 0;

    // **A guest's left click on something alive.** See `packet::UseEntity` for
    // why this exists at all at protocol 2. `item` is what they are holding,
    // which is the whole of how hard the hit lands, and the position is theirs,
    // because a struck animal is knocked away from whoever hit it.
    struct AttackRequest {
        i32 entityId = 0;
        int item = 0;
        double playerX = 0.0;
        double playerZ = 0.0;
    };
    virtual void attackEntity(const AttackRequest& request) { (void)request; }

    // **A guest's left click on the host's own player.** The one entity in the
    // session this server does not own: the host's health is the host's, the
    // way every player's is at protocol 2, so this hands the blow to whoever
    // is holding their vitals instead of resolving it here. `entityId` is the
    // host's and is not worth passing; what matters is who swung and with
    // what. See `net::IncomingHit`.
    virtual void attackHost(const AttackRequest& request) { (void)request; }

    // A line a guest typed, already prefixed with who said it, for the host's
    // own chat log.
    virtual void showChat(const std::string& line) = 0;

    // **What is lying on the ground.** The host's own pool -- an item dropped
    // by a guest is an ordinary item in this world, and one dropped here is an
    // ordinary item in theirs. Null for a world with no pool, which is what
    // the tests that do not care about items pass.
    virtual entity::ItemEntitySystem* items() { return nullptr; }

    // **What is alive.** The host runs every animal and monster -- their AI,
    // their physics and their despawn -- and the guests are told where they
    // are, exactly as a client is told by a server. Null for a world with no
    // pool.
    virtual entity::MobSystem* mobs() { return nullptr; }

    // **What is in flight or stuck in the ground**, the host's own pool. An
    // arrow a guest fires is fired here, on their behalf, and the guests are
    // told where every arrow is -- see `WorldServer::syncArrows`. Null for a
    // world with no pool.
    virtual entity::ArrowSystem* arrows() { return nullptr; }

    // **A guest's right click in the air** -- `makeUseItem`. Only the bow
    // means anything at protocol 2's end of the game: the host fires the
    // arrow from the guest's eye along their look, as theirs. The ammunition
    // is the guest's and was spent on their own console before they asked.
    struct UseRequest {
        int item = 0;
        i32 shooterEntityId = 0;
        double eyeX = 0.0, eyeY = 0.0, eyeZ = 0.0;
        float yawDegrees = 0.0f;
        float pitchDegrees = 0.0f;
    };
    virtual void useItem(const UseRequest& request) { (void)request; }

    // A guest threw something. `mx/my/mz` are blocks per tick.
    virtual void spawnItem(double x, double y, double z, item::ItemId id, int count,
                           double mx, double my, double mz)
    {
        (void)x; (void)y; (void)z; (void)id; (void)count; (void)mx; (void)my; (void)mz;
    }
};


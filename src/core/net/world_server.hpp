// The deflate thread. One column in, one 0x33's worth of encoded bytes out.
//
// Two slots deep rather than one, so the main thread can hand over the next
// column in the same frame it takes the last one back and the thread is never
// idle waiting for a frame to come round.
class ColumnOven {
public:
    static constexpr int kDepth = 2;

    ColumnOven() = default;
    ~ColumnOven();

    ColumnOven(const ColumnOven&) = delete;
    ColumnOven& operator=(const ColumnOven&) = delete;

    // False when no thread could be started, in which case `offer` deflates
    // inline -- slow, but a session rather than no session.
    bool start();
    void stop();
    bool threaded() const { return running_; }

    // Hands over one column's raw planes, which are taken from `raw`. False
    // when both slots are busy, and then `raw` is untouched.
    bool offer(u8 playerId, i32 chunkX, i32 chunkZ, std::vector<u8>* raw);

    // A finished Map Chunk, encoded. False when nothing is ready.
    bool take(u8* playerId, i32* chunkX, i32* chunkZ, std::vector<u8>* encoded);

    // How many are in the oven or waiting to be taken out.
    int outstanding() const;

private:
    enum class Slot : u8 { Free, Waiting, Baking, Done };

    struct Job {
        Slot slot = Slot::Free;
        u8 playerId = 0;
        i32 chunkX = 0;
        i32 chunkZ = 0;
        std::vector<u8> raw;
        std::vector<u8> encoded;
    };

    static void threadEntry(void* self);
    void run();
    static void bake(Job& job);

    mutable std::mutex lock_;
    std::condition_variable wake_;
    Job jobs_[kDepth];
    bool stopRequested_ = false;
    bool running_ = false;

    std::thread thread_;
    void* platformThread_ = nullptr;
};


#pragma once

// The host's half of a playable session: the world it has open, described to
// the other consoles in protocol-2 packets.
//
// **Why protocol 2 and not something of our own.** This console already has a
// complete protocol-2 *client* -- core/net/packets.hpp encodes and parses the
// table, core/net/chunk_payload.hpp makes and reads Map Chunks,
// `WorldStreamer::openRemote` runs a world nobody generates, and
// platform/ctr/net_play.hpp joins the two. All of that was written to talk to
// server 0.2.1 over TCP and none of it cares what carried the bytes. So a host
// that speaks the same packets gets the entire guest side for nothing, and the
// one thing that had to be built is this: the half that decides *what to say*.
//
// **The link is a byte stream, so this is a byte stream.** A protocol-2 packet
// has no length prefix -- the parser finds the next one by knowing the shape of
// this one -- so the packets are written end to end into a per-player buffer
// and the caller cuts that into link messages. core/net/link.hpp delivers them
// reliably and in order, which is the same promise TCP makes and the only one
// the parser needs.
//
// **What the host can serve is what the host has loaded -- and it loads for
// everybody.** The grid is a square around the host's own camera (see
// core/render/world_streamer.hpp: it wraps modulo its own width, so it has
// exactly one centre), so for a long time a column outside it could not be
// sent and a guest who walked past the edge of the host's render distance
// simply stopped receiving ground.
//
// `viewCentres` is the end of that. It says where every guest is; the streamer
// takes the list as **served areas** and holds their ground outside the grid,
// read from the same cache, generated by the same generator, ticked through the
// same `TickWorld` and saved by the same autosave -- everything a resident
// column gets except a mesh, which is the one thing nobody on this console is
// looking at. `Player::starved` still exists and still means "there is no
// column under them *right now*", but it is a wait while their ground is read
// or made rather than a wall they have walked into.
//
// **One thread, for the deflate.** A column is 82 KB of planes and
// `zip::compress` over it is several frames' work on an ARM11, which
// CONTRIBUTING has ruled off core 0 since long before there was a session.
// Serialising happens on the main thread, where the grid is settled and a
// borrowed column pointer is safe; only the deflate crosses. See `ColumnOven`.

